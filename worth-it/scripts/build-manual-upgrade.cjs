// Build the manual upgrade from canonical migrations. No database connection.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const names=[
 '0011_full_size_photos.sql','0012_safety_and_accounts.sql',
 '0013_media_and_pagination.sql','0014_results_and_engagement.sql',
 '0015_media_jobs.sql','0016_operations.sql','0017_post_management.sql',
];
const preflight=`
do $$
begin
 if to_regprocedure('public.worthit_manage_post(text,uuid,text,jsonb)') is not null then
  raise exception 'Post management is already installed. Do not rerun this upgrade.' using errcode='55000';
 end if;
 if to_regclass('public.polls') is null or to_regclass('public.social_comments') is null
 or to_regprocedure('public.discover_shopping_polls(text,integer,integer,text,boolean)') is null
 or not exists(select 1 from information_schema.columns where table_schema='public' and table_name='polls' and column_name='category')
 then raise exception 'This upgrade requires the existing schema through migration 0010. Run check_migrations.sql first.' using errcode='55000';end if;
 if exists(select 1 from unnest(array[
  'public.account_blocks','public.moderators','public.content_reports','public.daily_usage','public.account_deletion_requests',
  'public.saved_polls','public.notification_reads','public.product_feedback','public.media_jobs','public.media_pipeline_settings',
  'public.post_tombstones','public.post_media_cleanup','public.post_retired_media'
 ]) marker where to_regclass(marker) is not null)
 or to_regprocedure('public.worthit_discovery_unfiltered(text,integer,integer,text,boolean)') is not null
 or to_regprocedure('public.worthit_product_key(text)') is not null
 or exists(select 1 from information_schema.columns where table_schema='public' and (
 (table_name='social_profiles' and column_name='is_suspended') or
 (table_name in ('polls','social_reels') and column_name in ('archived_at','edited_at','media_state'))))
 then raise exception 'Some migrations after 0010 are already present. Run check_migrations.sql and apply only the missing migration files.' using errcode='55000';
 end if;
end $$;
`;
function buildUpgrade(sources){
 if(sources.length!==names.length||sources.some((source,index)=>source.name!==names[index]))throw new Error('Unexpected migration inputs');
 const sections=sources.map(({name,sql})=>{
  let body=sql.replace(/\r\n/g,'\n').trim();
  if(/^begin;/i.test(body)){
   if(!/commit;$/i.test(body))throw new Error('Missing outer commit in '+name);
   body=body.replace(/^begin;\s*/i,'').replace(/\s*commit;$/i,'');
  }
  return '-- Source: supabase/migrations/'+name+'\n'+body;
 });
 return '-- Manual upgrade for databases at 0010, with 0011-0017 missing.\n'+
 '-- Generated by scripts/build-manual-upgrade.cjs; do not edit this bundle directly.\n'+
 '-- Run the ENTIRE file once in Supabase SQL Editor. All changes commit together.\n'+
 '-- If any statement fails, the transaction does not commit.\n'+
 '-- CLI-managed projects should deploy the canonical migration files instead.\n\n'+
 'begin;\n'+preflight+'\n'+sections.join('\n\n')+'\n\ncommit;\n';
}
function sources(){return names.map(name=>({name,sql:fs.readFileSync(path.join(root,'supabase/migrations',name),'utf8')}));}
module.exports={buildUpgrade,sources};
if(require.main===module){
 fs.writeFileSync(path.join(root,'supabase/upgrade_0011_to_0017.sql'),buildUpgrade(sources()),'utf8');
 console.log('Built supabase/upgrade_0011_to_0017.sql');
}
